-- Schema, internal roles, and stores + control-plane tables.
-- The baseline is these files concatenated in name order:
--   cat Supabase-Setup/supabase/schemas/*.sql > Supabase-Setup/supabase/migrations/20261015000000_baseline.sql
-- Supabase's event-trigger helper, when the project has it, is not for API clients.
do $$ begin
  if to_regprocedure('public.rls_auto_enable()') is not null then
    revoke execute on function public.rls_auto_enable() from public, anon, authenticated, service_role;
  end if;
end $$;

create schema sadid_private;
revoke all on schema sadid_private from public, anon, authenticated, service_role;

create role sadid_ledger_executor nologin nosuperuser nobypassrls noinherit;
create role sadid_auth_reader nologin nosuperuser nobypassrls noinherit;
create role sadid_support_reader nologin nosuperuser nobypassrls noinherit;
grant sadid_ledger_executor, sadid_auth_reader, sadid_support_reader to postgres;
grant usage on schema public, sadid_private to sadid_ledger_executor, sadid_auth_reader, sadid_support_reader;
grant create on schema sadid_private to sadid_ledger_executor, sadid_auth_reader, sadid_support_reader;
grant usage on schema sadid_private to authenticated, service_role;

-- The caller's JWT claims, read as auth.jwt() reads them. Code that can run as an internal role
-- uses this instead of auth.uid()/auth.jwt(): on Supabase only supabase_auth_admin can grant
-- USAGE on schema auth, so the internal roles have none.
create function sadid_private.jwt_claims() returns jsonb
language sql stable security invoker set search_path = '' as $$
  select coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb, '{}'::jsonb)
$$;
revoke all on function sadid_private.jwt_claims() from public, anon, service_role;
grant execute on function sadid_private.jwt_claims() to authenticated, sadid_auth_reader, sadid_support_reader;

create table public.stores (
  id bigint generated by default as identity primary key,
  name text not null,
  username text not null,
  status text not null default 'active' check (status in ('active', 'suspended', 'deleted')),
  suspend_until bigint,
  verified boolean not null default false,
  debtor_limit integer not null default 100 check (debtor_limit >= 0),
  subscription_mode text not null default 'permanent' check (subscription_mode in ('permanent', 'timed', 'paused')),
  subscription_started_at bigint,
  subscription_expires_at bigint,
  subscription_paused_remaining_ms bigint,
  allowed_devices integer not null default 1 check (allowed_devices between 1 and 50),
  permissions jsonb not null default '{}'::jsonb,
  revision bigint not null default 0,
  created_at bigint not null default (extract(epoch from clock_timestamp()) * 1000)::bigint
);
create unique index stores_username_ci on public.stores (lower(username));

alter table public.stores enable row level security;
revoke all on public.stores from public, anon, authenticated;
grant all on public.stores to service_role;
grant usage, select on all sequences in schema public to service_role;
grant select on public.stores to sadid_auth_reader;
create policy sadid_auth_store_check on public.stores for select to sadid_auth_reader using (true);

create table sadid_private.store_memberships (
  user_id uuid primary key references auth.users(id) on delete restrict,
  store_id bigint not null unique references public.stores(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table sadid_private.installations (
  id uuid primary key,
  store_id bigint not null references public.stores(id) on delete restrict,
  generation integer not null check (generation > 0),
  public_key jsonb not null,
  label text not null default '',
  staff_name text not null default '',
  permissions jsonb not null default '{"registerPayments":true,"deleteRecords":true,"deleteContacts":true}'::jsonb,
  status text not null check (status in ('pending', 'active', 'revoked')),
  approved_by text,
  approved_at timestamptz,
  revoked_at timestamptz,
  reason text,
  created_at timestamptz not null default now(),
  unique (store_id, id, generation)
);
create index sadid_installations_store_status on sadid_private.installations(store_id, status);

create table sadid_private.capabilities (
  token_hash bytea primary key,
  user_id uuid not null,
  auth_session_id uuid not null,
  store_id bigint not null,
  installation_id uuid not null,
  generation integer not null,
  scope text not null check (scope in ('read', 'write', 'lease')),
  request jsonb,
  recovery_permit_id uuid,
  issued_at timestamptz not null default clock_timestamp(),
  expires_at timestamptz not null,
  foreign key (store_id, installation_id, generation) references sadid_private.installations(store_id, id, generation)
);
create index sadid_capability_expiry on sadid_private.capabilities(expires_at);
create index sadid_capability_user on sadid_private.capabilities(user_id, auth_session_id);
create index sadid_capabilities_installation_fk on sadid_private.capabilities(store_id, installation_id, generation);

create table sadid_private.request_nonces (
  installation_id uuid not null references sadid_private.installations(id),
  nonce uuid not null,
  created_at timestamptz not null default now(),
  primary key (installation_id, nonce)
);
create index sadid_nonce_rate on sadid_private.request_nonces(installation_id, created_at);

create table sadid_private.recovery_permits (
  id uuid primary key default gen_random_uuid(),
  store_id bigint not null,
  user_id uuid not null,
  old_installation_id uuid not null references sadid_private.installations(id),
  new_installation_id uuid not null references sadid_private.installations(id),
  old_generation integer not null,
  manifest jsonb not null,
  manifest_hash bytea not null,
  approved_by text not null,
  reason text not null,
  epoch uuid,
  created_at timestamptz not null default clock_timestamp(),
  expires_at timestamptz not null
);
create index sadid_recovery_old_installation_fk on sadid_private.recovery_permits(old_installation_id);
create index sadid_recovery_new_installation_fk on sadid_private.recovery_permits(new_installation_id);
create index sadid_recovery_store on sadid_private.recovery_permits(store_id, created_at desc);

create table sadid_private.control_events (
  id bigint generated always as identity primary key,
  store_id bigint not null,
  actor text not null,
  kind text not null,
  reason text not null,
  details jsonb not null default '{}',
  created_at timestamptz not null default clock_timestamp()
);
create index sadid_control_events_store on sadid_private.control_events(store_id, id desc);

create table sadid_private.admin_access_events (
  id uuid primary key default gen_random_uuid(),
  store_id bigint not null,
  actor text not null,
  reason text not null,
  outcome text not null,
  record_counts jsonb not null,
  created_at timestamptz not null default clock_timestamp()
);
create index sadid_admin_access_events_store on sadid_private.admin_access_events(store_id, created_at desc);

do $$ declare t text; begin
  foreach t in array array['store_memberships', 'installations', 'capabilities', 'request_nonces', 'recovery_permits', 'control_events'] loop
    execute format('alter table sadid_private.%I enable row level security', t);
    execute format('revoke all on sadid_private.%I from public, anon, authenticated, service_role', t);
    execute format('grant select on sadid_private.%I to sadid_auth_reader', t);
    execute format('create policy internal_reader on sadid_private.%I for select to sadid_auth_reader using (true)', t);
  end loop;
end $$;

grant select on sadid_private.store_memberships to authenticated, service_role;
create policy own_membership on sadid_private.store_memberships for select to authenticated using (user_id = (select auth.uid()));

alter table sadid_private.admin_access_events enable row level security;
revoke all on sadid_private.admin_access_events from public, anon, authenticated, service_role;
grant insert on sadid_private.admin_access_events to sadid_support_reader;

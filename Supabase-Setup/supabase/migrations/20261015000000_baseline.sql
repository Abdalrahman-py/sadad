    'status', t.status,
    'createdAt', t.created_at
  ) order by t.created_at desc, t.id desc), '[]'::jsonb) into v_rows
  from (
    select i.*, s.name as store_name
    from sadid_private.installations i
    join public.stores s on s.id = i.store_id

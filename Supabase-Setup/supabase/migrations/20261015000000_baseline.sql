-- Serializes ledger writes per store and pins the installation and session.
create function sadid_private.lock_authorization() returns void
language plpgsql security definer set search_path = '' as $$
declare c sadid_private.capabilities;
begin
  c := sadid_private.current_capability();
  if c.store_id is null then raise exception 'authorization_required'; end if;
  perform 1 from public.stores where id = c.store_id for update;
  perform 1 from sadid_private.installations where id = c.installation_id for share;
  perform 1 from auth.sessions where id = c.auth_session_id and user_id = c.user_id for share;
end $$;
revoke all on function sadid_private.lock_authorization() from public, anon, authenticated, service_role;
grant execute on function sadid_private.lock_authorization() to sadid_ledger_executor;
-- Store and installation permissions for one operation type.
create function sadid_private.operation_allowed(p_kind text) returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(
    (s.permissions ->> case
      when p_kind like 'contact.%' then 'contacts'
      when p_kind like 'debt.%' then 'debts'
      when p_kind like 'payment.%' then 'payments'
      else 'invalid'
    end)::boolean,
    true
  )
  and coalesce(
    (i.permissions ->> case
      when p_kind in ('payment.create', 'payment.reverse') then 'registerPayments'
      when p_kind in ('contact.archive', 'contact.restore') then 'deleteContacts'
      when p_kind = 'debt.correct' then 'deleteRecords'
      else 'allowed'
    end)::boolean,
    true
  )
  from sadid_private.current_capability() c
  join public.stores s on s.id = c.store_id
  join sadid_private.installations i on i.id = c.installation_id and i.store_id = c.store_id and i.generation = c.generation
$$;
